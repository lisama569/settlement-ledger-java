-- V1: 结算指令、审计事件、幂等记录基础结构
CREATE TABLE settlement_instructions (
    instruction_id   VARCHAR(64)  PRIMARY KEY,
    debtor_account   VARCHAR(64)  NOT NULL,
    creditor_account VARCHAR(64)  NOT NULL,
    amount           DECIMAL(18,2) NOT NULL,
    currency         VARCHAR(8)   NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    version          BIGINT       NOT NULL,
    submitted_by     VARCHAR(64)  NOT NULL,
    rejection_reason VARCHAR(256),
    created_at      TIMESTAMP(6) NOT NULL,
    updated_at      TIMESTAMP(6) NOT NULL
);

CREATE TABLE settlement_events (
    seq_no         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instruction_id VARCHAR(64) NOT NULL,
    event_type     VARCHAR(32) NOT NULL,
    payload_version INT        NOT NULL,
    payload        CLOB        NOT NULL,
    occurred_at    TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_events_instruction ON settlement_events (instruction_id, seq_no);

CREATE TABLE idempotency_records (
    idempotency_key  VARCHAR(128) PRIMARY KEY,
    instruction_id   VARCHAR(64)  NOT NULL,
    request_fingerprint VARCHAR(128) NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL
);
